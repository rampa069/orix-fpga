#!/usr/bin/env python3
"""Turn the 32 KB CH376 firmware image into a VHDL package.

Usage: mkrom.py ch376fw.bin ../../rtl/ch376_fw_rom.vhd

The package holds the ROM contents as a constant, so the same file works
for simulation (nvc, GHDL) and for Quartus, which infers an initialised
block RAM from it.
"""

import sys

ROM_SIZE = 32768


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    if len(data) != ROM_SIZE:
        sys.exit(f"{sys.argv[1]}: {len(data)} bytes, expected {ROM_SIZE}")

    out = []
    out.append("-- ch376_fw_rom")
    out.append("-- Firmware of the CH376 softcore. Generated by firmware/ch376/mkrom.py")
    out.append("-- from firmware/ch376, do not edit.")
    out.append("")
    out.append("LIBRARY IEEE;")
    out.append("USE IEEE.STD_LOGIC_1164.ALL;")
    out.append("")
    out.append("PACKAGE ch376_fw_rom IS")
    out.append(f"\tTYPE ch376_rom_t IS ARRAY(0 TO {ROM_SIZE - 1}) OF STD_LOGIC_VECTOR(7 DOWNTO 0);")
    out.append("\tCONSTANT CH376_FW : ch376_rom_t := (")
    lines = []
    for i in range(0, ROM_SIZE, 16):
        chunk = ", ".join(f'x"{b:02X}"' for b in data[i:i + 16])
        lines.append(f"\t\t{chunk}")
    out.append(",\n".join(lines))
    out.append("\t);")
    out.append("END PACKAGE;")
    out.append("")
    with open(sys.argv[2], "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
